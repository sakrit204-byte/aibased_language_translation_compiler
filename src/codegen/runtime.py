_helper("py_round_half_even")("""
/* Python rounds halves to even: round(0.5) == 0, round(2.5) == 2, round(3.5) == 4.
 * C's round() goes half away from zero, so the tie is corrected explicitly.
 * Transliterated from CPython's float___round___impl. */
static py_float py_round_half_even(py_float x)
{
    py_float r = round(x);
    if (fabs(x - r) == 0.5) r = 2.0 * round(x / 2.0);
    return r;
}
""")


_helper("py_round_int", ["py_round_half_even", "py_fatal"])("""
static py_int py_round_int(py_float x)
{
    py_float r;
    if (isnan(x)) py_fatal("ValueError: cannot convert float NaN to integer");
    if (isinf(x)) py_fatal("OverflowError: cannot convert float infinity to integer");
    r = py_round_half_even(x);
    if (r < -9.2233720368547758e18 || r > 9.2233720368547758e18)
        py_fatal("OverflowError: rounded value too large for a 64-bit integer");
    return (py_int)r;
}
""")


_helper("py_round_float", ["py_round_half_even"])("""
static py_float py_round_float(py_float x, py_int ndigits)
{
    if (!isfinite(x)) return x;
    if (ndigits >= 0) {
        char buf[512];
        if (ndigits > 17) return x;          /* beyond a double's precision */
        snprintf(buf, sizeof buf, "%.*f", (int)ndigits, x);
        return strtod(buf, NULL);
    } else {
        py_float scale;
        if (ndigits < -308) return 0.0 * x;  /* preserves the sign of zero */
        scale = pow(10.0, (py_float)(-ndigits));
        return py_round_half_even(x / scale) * scale;
    }
}
""")


_helper("py_round_int_ndigits")("""
/* round(int, ndigits): Python keeps the value an int and still rounds halves
 * to even, so round(1250, -2) is 1200 but round(1350, -2) is 1400. */
static py_int py_round_int_ndigits(py_int x, py_int nd)
{
    py_int scale = 1, i, q, r;
    if (nd >= 0) return x;
    if (nd < -18) return 0;
    for (i = 0; i < -nd; i++) scale *= 10;
    q = x / scale;
    r = x % scale;
    if (r < 0) { r += scale; q -= 1; }       /* floor form: 0 <= r < scale */
    if (2 * r > scale || (2 * r == scale && (q % 2) != 0)) q += 1;
    return q * scale;
}
""")


_helper("py_int_from_float", ["py_fatal"])("""
static py_int py_int_from_float(py_float x)
{
    py_float t;
    if (isnan(x)) py_fatal("ValueError: cannot convert float NaN to integer");
    if (isinf(x)) py_fatal("OverflowError: cannot convert float infinity to integer");
    t = trunc(x);                            /* int() truncates toward zero */
    if (t < -9.2233720368547758e18 || t > 9.2233720368547758e18)
        py_fatal("OverflowError: float too large to convert to a 64-bit integer");
    return (py_int)t;
}
""")


_helper("py_int_from_str", ["py_fatal"])("""
static py_int py_int_from_str(py_str s)
{
    char *end;
    long long v;
    if (s == NULL) py_fatal("ValueError: invalid literal for int()");
    v = strtoll(s, &end, 10);
    if (end == s) py_fatal("ValueError: invalid literal for int() with base 10");
    while (*end == ' ' || *end == '\\t' || *end == '\\n' || *end == '\\r') end++;
    if (*end != '\\0') py_fatal("ValueError: invalid literal for int() with base 10");
    return (py_int)v;
}
""")


_helper("py_float_from_str", ["py_fatal"])("""
static py_float py_float_from_str(py_str s)
{
    char *end;
    py_float v;
    if (s == NULL) py_fatal("ValueError: could not convert string to float");
    v = strtod(s, &end);
    if (end == s) py_fatal("ValueError: could not convert string to float");
    while (*end == ' ' || *end == '\\t' || *end == '\\n' || *end == '\\r') end++;
    if (*end != '\\0') py_fatal("ValueError: could not convert string to float");
    return v;
}
""")


