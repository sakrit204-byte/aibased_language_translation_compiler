_helper("py_repr_float")("""
/* repr() of a float: the shortest decimal string that reads back as the same
 * double, which is why print(0.1) is "0.1" and not "0.100000".
 *
 * Mirrors CPython's format_float_short: find the smallest precision that
 * round-trips, then use positional notation when the decimal exponent is in
 * [-4, 16) and scientific notation outside it. */
static void py_repr_float(char *out, size_t cap, py_float v)
{
    char tmp[64];
    const char *epos;
    int p, exp10, dec;

    if (isnan(v)) { snprintf(out, cap, "nan"); return; }
    if (isinf(v)) { snprintf(out, cap, v < 0 ? "-inf" : "inf"); return; }

    for (p = 1; p < 17; p++) {
        snprintf(tmp, sizeof tmp, "%.*e", p - 1, v);
        if (strtod(tmp, NULL) == v) break;
    }
    snprintf(tmp, sizeof tmp, "%.*e", p - 1, v);

    epos = strchr(tmp, 'e');
    exp10 = epos ? (int)strtol(epos + 1, NULL, 10) : 0;

    if (exp10 >= -4 && exp10 < 16) {
        dec = p - 1 - exp10;
        if (dec < 0) dec = 0;
        snprintf(out, cap, "%.*f", dec, v);
        if (strchr(out, '.') == NULL) {
            size_t n = strlen(out);
            if (n + 3 <= cap) { out[n] = '.'; out[n + 1] = '0'; out[n + 2] = '\\0'; }
        }
    } else {
        snprintf(out, cap, "%s", tmp);
    }
}
""")


# print() writes its arguments separated by a single space and ends the line.
# C cannot dispatch on type, so codegen emits one call per argument and asks
# only for the per-type helpers the program actually uses.

_helper("py_print")("""
/* print() support: one call per argument, separated by a single space. */
static int py__print_first = 1;

static void py_print_begin(void) { py__print_first = 1; }

static void py__print_sep(void)
{
    if (!py__print_first) putchar(' ');
    py__print_first = 0;
}

static void py_print_end(void) { putchar('\\n'); py__print_first = 1; }
""")


_helper("py_print_int", ["py_print"])("""
static void py_print_int(py_int v) { py__print_sep(); printf("%lld", (long long)v); }
""")


_helper("py_print_bool", ["py_print"])("""
static void py_print_bool(py_bool v) { py__print_sep(); fputs(v ? "True" : "False", stdout); }
""")


_helper("py_print_str", ["py_print"])("""
static void py_print_str(py_str s) { py__print_sep(); fputs(s ? s : "", stdout); }
""")


_helper("py_print_float", ["py_print", "py_repr_float"])("""
static void py_print_float(py_float v)
{
    char buf[64];
    py_repr_float(buf, sizeof buf, v);
    py__print_sep();
    fputs(buf, stdout);
}
""")


def prelude_for(needed) -> str:
    """Return the header plus every requested helper and its dependencies,
    in declaration order."""
    resolved = []
    seen = set()

    def add(name):
        if name in seen:
            return
        if name not in HELPERS:
            raise KeyError(f"unknown runtime helper {name!r}")
        seen.add(name)
        for dep in HELPERS[name][0]:
            add(dep)
        resolved.append(name)

    for name in HELPERS:            # fixed order, independent of request order
        if name in needed:
            add(name)

    parts = [HEADER]
    if resolved:
        parts.append("\n/* ---- runtime helpers ---- */\n")
        for name in resolved:
            parts.append(HELPERS[name][1])
    return "".join(parts)
